/**
 * Function to generate additional blog posts (for demonstration purposes)
 * 
 * This function creates additional sample blog posts to demonstrate pagination.
 * In a real implementation, you would replace these with your actual blog posts.
 */
const generateAdditionalPosts = (count: number) => {
  const additionalPosts = [];
  const tags = ["Instagram", "Travel", "Photography", "Lifestyle", "Creativity", "Sustainability", "Personal", "Technology"];
  
  // Starting from the last ID in the existing posts
  let startId = sampleData.blogPosts.length + 1;
  
  for (let i = 0; i < count; i++) {
    // Generate random tags (2-3 tags per post)
    const postTags = [];
    const numTags = Math.floor(Math.random() * 2) + 2; // 2-3 tags
    
    for (let j = 0; j < numTags; j++) {
      const randomTag = tags[Math.floor(Math.random() * tags.length)];
      if (!postTags.includes(randomTag)) {
        postTags.push(randomTag);
      }
    }
    
    // Generate a post with a unique ID
    additionalPosts.push({
      id: startId + i,
      title: `Sample Blog Post ${startId + i}`,
      description: `This is a sample description for blog post number ${startId + i}. Replace this with your actual blog post content.`,
      content: `This is the full content for blog post number ${startId + i}. In a real implementation, this would be your complete blog post text, possibly formatted with markdown or HTML.`,
      date: `January ${1 + i}, 2024`,
      tags: postTags,
      slug: `sample-post-${startId + i}`
    });
  }
  
  return additionalPosts;
};

